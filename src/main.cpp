// curvy - node based 2D vector editor.
//
//   curvy.exe                       opens the workspace: a top bar, an empty canvas, the dock areas and the hint bar; Space opens the ring menu
//   curvy.exe --settings <file>     keeps theme, window and dock state in that file (default <local app data>/curvy/settings.json5)
//   curvy.exe --open <file>         opens a .curvy file at start
//   curvy.exe --dump-views          loads the layout, lays it out, prints the view tree (--depth=N, default 4) and exits
//   curvy.exe --automation <pipe>   serves the window to a GUI test driver (only in a build with CURVY_GUI_AUTOMATION)
//
// Unit tests are in tests/ (curvyTests).

#ifdef CURVY_GUI_AUTOMATION
#include "newui/automation.h"
#endif
#include "newui/application.h"
#include "newui/bundle.h"
#include "newui/frame.h"
#include "newui/rootview.h"

#include "curvy/settings.h"
#include "curvy/workspacecontroller.h"

#include <cstdio>
#include <string>
#include <typeinfo>

// Both generated by reflectgen - nothing calls them automatically for a standalone exe. newui's own classes first (curvy's classes
// derive from them), then curvy's.
extern void registerReflectionData();
extern void registerCurvyReflection();

namespace {

    struct Options {
        bool dumpViews = false;
        std::string openPath;
        std::string settingsPath;
        std::string automationPipe;
        int dumpDepth = 4;
    };

    Options parseOptions(int argc, char** argv) {
        Options options;
        for (int i = 1; i < argc; ++i) {
            const std::string arg = argv[i];
            if (arg == "--dump-views") {
                options.dumpViews = true;
            } else if (arg == "--settings" && i + 1 < argc) {
                options.settingsPath = argv[++i];
            } else if (arg == "--open" && i + 1 < argc) {
                options.openPath = argv[++i];
            } else if (arg == "--automation" && i + 1 < argc) {
                options.automationPipe = argv[++i];
            } else if (arg.rfind("--depth=", 0) == 0) {
                options.dumpDepth = std::stoi(arg.substr(8));
            }
        }
        return options;
    }

    void dumpTree(const newui::View& view, int depth, int maxDepth) {
        const newui::Rect& b = view.bounds();
        std::printf("%*s%s \"%s\" [%.0f,%.0f %.0fx%.0f]%s\n", depth * 2, "", typeid(view).name(),
            view.name().c_str(), b.left(), b.top(), b.width(), b.height(), view.isVisible() ? "" : " (hidden)");
        if (depth >= maxDepth) {
            return;
        }
        for (const newui::SubView* child : view.childViews()) {
            dumpTree(*child, depth + 1, maxDepth);
        }
    }
}

int main(int argc, char** argv) {
    registerReflectionData();
    registerCurvyReflection();
    const Options options = parseOptions(argc, argv);

    // Dumping the view tree reads and writes no settings.
    const std::string settingsPath = options.dumpViews ? std::string() : (options.settingsPath.empty() ? curvy::Settings::defaultPath() : options.settingsPath);
    curvy::Settings settings = curvy::Settings::load(settingsPath);
    curvy::WorkspaceController::applyTheme(settings.darkTheme());
    newui::Frame frame;
    newui::Application& app = newui::Application::instance();
    app.setName("curvy");
    app.setFrame(&frame);

    // Bundle::loadFrame() resolves "Resources/<frame name>.newui" next to the exe; CMake copies Resources there after each build.
    frame.setName("workspace");
    if (!newui::Bundle::instance().loadFrame(frame)) {
        std::printf("curvy: could not load Resources/workspace.newui\n");
        return 1;
    }
    if (options.dumpViews) {
        frame.rootView().updateLayout();
        dumpTree(frame.rootView(), 0, options.dumpDepth);
        return 0;
    }

    curvy::WorkspaceController window(frame, settings, settingsPath);   // builds its views when the window is created, inside app.run()
    window.restoreWindow();
    if (!options.openPath.empty()) {
        app.runLoop().post([&window, path = options.openPath]() { window.openFile(path); });   // the worker and its timer need the loop running
    }
#ifdef CURVY_GUI_AUTOMATION
    if (!options.automationPipe.empty()) {
        newui::Automation::expose(frame.rootView());
        newui::Automation::start(options.automationPipe, app.runLoop());
    }
#endif
    app.run();
#ifdef CURVY_GUI_AUTOMATION
    newui::Automation::stop();
#endif
    return 0;
}
