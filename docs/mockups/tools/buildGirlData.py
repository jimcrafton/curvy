import json, sys
from collections import defaultdict
import os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from girlParse import load

SRC = sys.argv[1]
OUT = sys.argv[2]
fills, grads, shapes = load(SRC)

SKIN = {'fil1', 'fil3', 'fil4', 'fil5', 'fil6', 'fil7', 'fil8', 'fil9', 'fil10', 'fil11', 'fil12', 'fil13', 'fil14', 'fil15', 'fil16', 'fil18', 'fil21', 'fil52', 'fil53', 'fil54', 'fil51'}
SHIRT = {'fil19', 'fil41', 'fil42', 'fil43', 'fil44', 'fil45', 'fil46', 'fil47', 'fil48', 'fil49', 'fil50'}
DARK = {'fil22', 'fil26', 'fil27', 'fil28', 'fil29', 'fil30', 'fil34', 'fil40'}
TEAL = {'fil23', 'fil24', 'fil25', 'fil31', 'fil32', 'fil33', 'fil35', 'fil36', 'fil39'}

def group(s):
    c = s['c']; b = s['b']; cx = (b[0] + b[2]) / 2; cy = (b[1] + b[3]) / 2
    if c == 'fil0': return 'Background'
    if c == 'fil20': return 'Line art'
    if c in ('fil55', 'fil37', 'fil38'): return 'Stars'
    if c in ('fil2', 'fil17'): return 'Birds'
    if c in SKIN: return 'Hand' if (cx > 15000 and cy < 17000) else 'Face'
    if c in SHIRT: return 'Shirt'
    if c in DARK: return 'Hair' if cy > 13500 else 'Night sky'
    if c in TEAL: return 'Cloud wash'
    return 'Other'

order = ['Background', 'Night sky', 'Cloud wash', 'Hair', 'Birds', 'Stars', 'Face', 'Hand', 'Shirt', 'Line art', 'Other']
for s in shapes: s['g'] = group(s)
counts = defaultdict(int)
for s in shapes: counts[s['g']] += 1
groups = [{'name': g, 'n': counts[g]} for g in order if counts[g]]
print({g['name']: g['n'] for g in groups})
data = {'vb': 30038, 'fills': fills, 'grads': grads, 'groups': groups, 'shapes': shapes}
open(OUT, 'w', encoding='utf8').write('/* generated by tools/buildGirlData.py from an SVG illustration (estimate of an import) */\nconst GIRL = ' + json.dumps(data, separators=(',', ':')) + ';\n')
